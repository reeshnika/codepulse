class NumberedCanvas(canvas.Canvas):
    """Custom canvas that tracks page numbers and draws a footer on all pages."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_footer(num_pages)
            super().showPage()
        super().save()

    def draw_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        footer_text = f"Generated by CodePulse © 2026  |  Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 40, 25, footer_text)
        self.drawString(40, 25, "Confidential — Developer Intelligence Report")
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(40, 38, A4[0] - 40, 38)
        self.restoreState()


class ReportGenerator:
    """Produces publication-ready PDF analytics for CodePulse telemetry."""

    def __init__(self, data_dir=None):
        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        self.data_dir = data_dir or os.path.join(base_dir, 'data')

    @staticmethod
    def _format_duration(seconds):
        seconds = int(float(seconds or 0))
        hours = seconds // 3600
        minutes = (seconds % 3600) // 60
        secs = seconds % 60
        if hours > 0:
            return f"{hours}h {minutes}m {secs}s"
        elif minutes > 0:
            return f"{minutes}m {secs}s"
        return f"{secs}s"

    def generate_session_pdf(self, session_id, session_data=None, flow_data=None, output_path=None):
        """
        Creates a comprehensive A4 session report PDF.
        """
        if output_path is None:
            output_path = os.path.join(self.data_dir, f"codepulse_report_{session_id}.pdf")

        # Load file data if not provided directly
        if session_data is None:
            candidate = os.path.join(self.data_dir, f"session_{session_id}.json")
            if os.path.exists(candidate):
                try:
                    with open(candidate, 'r', encoding='utf-8') as f:
                        session_data = json.load(f)
                except Exception:
                    session_data = {}
            else:
                session_data = {}

        if flow_data is None:
            flow_data = session_data.get('flow_score', {})

        stats = session_data.get('keystroke_stats', {})
        code_stats = session_data.get('code_stats', {})
        cp_stats = session_data.get('copy_paste_stats', {})
        lang_stats = session_data.get('language_stats', {})
        fingerprint = session_data.get('fingerprint', 'N/A')
        timestamp_str = session_data.get('timestamp') or datetime.now().isoformat()

        doc = SimpleDocTemplate(
            output_path,
            pagesize=A4,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=45
        )

        styles = getSampleStyleSheet()
        normal = styles['Normal']

        title_style = ParagraphStyle(
            'HeaderTitle',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#00d4ff'),
            alignment=1
        )
        subtitle_style = ParagraphStyle(
            'HeaderSub',
            parent=normal,
            fontName='Helvetica',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#94a3b8'),
            alignment=1
        )
        section_style = ParagraphStyle(
            'SecTitle',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=16,
            textColor=colors.HexColor('#0f172a'),
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'Body',
            parent=normal,
            fontName='Helvetica',
            fontSize=9.5,
            leading=13,
            textColor=colors.HexColor('#1e293b')
        )
        table_cell_style = ParagraphStyle(
            'TableCell',
            parent=normal,
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#1e293b')
        )
        table_cell_bold = ParagraphStyle(
            'TableCellB',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#0f172a')
        )

        elements = []

        # Header Block
        header_data = [
            [Paragraph("CodePulse Session Report", title_style)],
            [Paragraph("Developer Intelligence Platform", subtitle_style)]
        ]
        header_table = Table(header_data, colWidths=[A4[0] - 72])
        header_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#0a0e17')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 0), (-1, -1), 14),
            ('BOTTOMPADDING', (0, -1), (-1, -1), 14),
            ('BOTTOMMARGIN', (0, 0), (-1, -1), 12),
        ]))
        elements.append(header_table)
        elements.append(Spacer(1, 14))

        # Section 1: Session Info
        elements.append(Paragraph("1. Session Information", section_style))
        duration_fmt = self._format_duration(stats.get('session_duration', 0))
        total_keys = stats.get('total_events', stats.get('presses', 0))
        wpm_val = stats.get('wpm', 0.0)
        if not wpm_val and stats.get('session_duration', 0) > 0 and stats.get('presses', 0) > 0:
            wpm_val = (stats.get('presses', 0) / 5.0) / (stats.get('session_duration', 1) / 60.0)
        bk_rate = stats.get('backspace_rate', 0.0)

        info_data = [
            [Paragraph("Session ID", table_cell_bold), Paragraph(str(session_id), table_cell_style),
             Paragraph("Date & Time", table_cell_bold), Paragraph(str(timestamp_str).replace('T', ' ')[:19], table_cell_style)],
            [Paragraph("Duration", table_cell_bold), Paragraph(duration_fmt, table_cell_style),
             Paragraph("Total Keystrokes", table_cell_bold), Paragraph(str(total_keys), table_cell_style)],
            [Paragraph("Typing Speed", table_cell_bold), Paragraph(f"{float(wpm_val):.1f} WPM", table_cell_style),
             Paragraph("Backspace Rate", table_cell_bold), Paragraph(f"{float(bk_rate) * 100:.1f}%", table_cell_style)],
        ]
        info_table = Table(info_data, colWidths=[110, 150, 110, 150])
        info_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f8fafc')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(info_table)
        elements.append(Spacer(1, 12))

        # Section 2: Flow Score Analysis
        elements.append(Paragraph("2. Flow Score Analysis", section_style))
        score = float(flow_data.get('score', 0.0) if isinstance(flow_data, dict) else flow_data)
        state = flow_data.get('state', 'WORKING') if isinstance(flow_data, dict) else 'WORKING'
        components = flow_data.get('components', {}) if isinstance(flow_data, dict) else {}

        flow_data_rows = [
            [Paragraph(f"<b>Overall Score:</b> {score:.1f} / 100", table_cell_bold),
             Paragraph(f"<b>Classification:</b> {state}", table_cell_bold)],
            [Paragraph("<b>Component</b>", table_cell_bold), Paragraph("<b>Score / 100</b>", table_cell_bold)],
            [Paragraph("Speed", table_cell_style), Paragraph(f"{components.get('speed', 0):.0f} / 100", table_cell_style)],
            [Paragraph("Accuracy", table_cell_style), Paragraph(f"{components.get('accuracy', 0):.0f} / 100", table_cell_style)],
            [Paragraph("Focus", table_cell_style), Paragraph(f"{components.get('focus', 0):.0f} / 100", table_cell_style)],
            [Paragraph("Clarity", table_cell_style), Paragraph(f"{components.get('clarity', 0):.0f} / 100", table_cell_style)],
            [Paragraph("Consistency", table_cell_style), Paragraph(f"{components.get('consistency', 0):.0f} / 100", table_cell_style)],
        ]
        flow_table = Table(flow_data_rows, colWidths=[260, 260])
        flow_table.setStyle(TableStyle([
            ('SPAN', (0, 0), (0, 0)),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (-1, 1), colors.HexColor('#f1f5f9')),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(flow_table)
        elements.append(Spacer(1, 12))

        # Section 3: Code Analysis
        elements.append(Paragraph("3. Code Analysis", section_style))
        code_changes = code_stats.get('total_changes', 0)
        avg_edit = code_stats.get('avg_edit_distance', 0.0)
        avg_sim = code_stats.get('avg_similarity', 1.0)
        lang_str = ", ".join([f"{k} ({v})" for k, v in lang_stats.items()]) if lang_stats else "General Code"

        code_rows = [
            [Paragraph("Total Code Changes", table_cell_bold), Paragraph(str(code_changes), table_cell_style),
             Paragraph("Average Edit Distance", table_cell_bold), Paragraph(f"{float(avg_edit):.1f} chars", table_cell_style)],
            [Paragraph("Average Code Similarity", table_cell_bold), Paragraph(f"{float(avg_sim) * 100:.1f}%", table_cell_style),
             Paragraph("Top Languages", table_cell_bold), Paragraph(lang_str, table_cell_style)],
        ]
        code_table = Table(code_rows, colWidths=[130, 130, 130, 130])
        code_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f8fafc')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(code_table)
        elements.append(Spacer(1, 12))

        # Section 4: Copy-Paste Analysis
        elements.append(Paragraph("4. Copy-Paste Activity", section_style))
        copies = cp_stats.get('total_copy', 0)
        pastes = cp_stats.get('total_paste', 0)
        suspicious = "Yes (Elevated)" if cp_stats.get('is_suspicious', pastes > 3) else "No (Normal)"

        cp_rows = [
            [Paragraph("Total Copies", table_cell_bold), Paragraph(str(copies), table_cell_style),
             Paragraph("Total Pastes", table_cell_bold), Paragraph(str(pastes), table_cell_style),
             Paragraph("Suspicious Flag", table_cell_bold), Paragraph(suspicious, table_cell_style)]
        ]
        cp_table = Table(cp_rows, colWidths=[86, 86, 86, 86, 92, 84])
        cp_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (4, 0), (4, -1), colors.HexColor('#f8fafc')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(cp_table)
        elements.append(Spacer(1, 12))

        # Section 5: Developer Fingerprint
        elements.append(Paragraph("5. Developer Fingerprint", section_style))
        fp_rows = [
            [Paragraph("Fingerprint Hash", table_cell_bold), Paragraph(f"<code>{fingerprint}</code>", table_cell_style),
             Paragraph("Timestamp", table_cell_bold), Paragraph(str(timestamp_str).replace('T', ' ')[:19], table_cell_style)]
        ]
        fp_table = Table(fp_rows, colWidths=[120, 140, 100, 160])
        fp_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f8fafc')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(fp_table)
        elements.append(Spacer(1, 12))

        # Section 6: Recommendations
        elements.append(Paragraph("6. Recommendations", section_style))
        recs = []
        if score >= 85:
            recs.append("• 🚀 Exceptional focus and flow state maintained. Great session!")
        elif score < 50:
            recs.append("• 🧠 Cognitive fatigue detected. Take a short 5-minute break before the next sprint.")

        spd = components.get('speed', 70)
        acc = components.get('accuracy', 70)
        foc = components.get('focus', 70)

        if spd < 50:
            recs.append("• Try typing faster to improve flow cadence.")
        if acc < 60:
            recs.append("• Reduce backspace errors for better focus and smoother syntax entry.")
        if foc < 50:
            recs.append("• Minimize pause times between statements by planning architecture before typing.")
        if pastes > 4:
            recs.append("• Review extensive external pastes to ensure original comprehension.")

        if not recs:
            recs.append("• Consistent rhythm and syntax entry observed across this session.")

        rec_table_data = [[Paragraph("<br/>".join(recs), body_style)]]
        rec_table = Table(rec_table_data, colWidths=[A4[0] - 72])
        rec_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#eff6ff')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#93c5fd')),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('LEFTPADDING', (0, 0), (-1, -1), 10),
            ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ]))
        elements.append(rec_table)

        doc.build(elements, canvasmaker=NumberedCanvas)
        return output_path

    def generate_weekly_summary_pdf(self, days=7, output_path=None):
        """
        Creates an aggregated N-day weekly intelligence summary PDF.
        """
        if output_path is None:
            output_path = os.path.join(self.data_dir, "codepulse_weekly_report.pdf")

        # Query session files from data folder
        cutoff = datetime.now() - timedelta(days=days)
        files = glob.glob(os.path.join(self.data_dir, "*.json"))

        recent_sessions = []
        for f in files:
            try:
                mtime = datetime.fromtimestamp(os.path.getmtime(f))
                if mtime >= cutoff:
                    with open(f, 'r', encoding='utf-8') as handle:
                        data = json.load(handle)
                    if isinstance(data, list):
                        data = data[-1] if data else {}
                    if isinstance(data, dict):
                        data['_mtime'] = mtime
                        recent_sessions.append(data)
            except Exception:
                continue

        total_sessions = len(recent_sessions)
        total_time = sum(s.get('keystroke_stats', {}).get('session_duration', 0) for s in recent_sessions)

        scores = []
        daily_buckets = {}
        for i in range(days):
            day_str = (datetime.now() - timedelta(days=days - 1 - i)).strftime("%Y-%m-%d")
            daily_buckets[day_str] = []

        for s in recent_sessions:
            score = s.get('flow_score', {}).get('score', 0) if isinstance(s.get('flow_score'), dict) else s.get('flow_score', 0)
            try:
                score = float(score)
            except (ValueError, TypeError):
                score = 0.0
            scores.append(score)
            day_key = s['_mtime'].strftime("%Y-%m-%d")
            if day_key in daily_buckets:
                daily_buckets[day_key].append(score)

        avg_flow = sum(scores) / len(scores) if scores else 0.0

        daily_avgs = {}
        for d, sc_list in daily_buckets.items():
            daily_avgs[d] = sum(sc_list) / len(sc_list) if sc_list else 0.0

        best_day = max(daily_avgs.items(), key=lambda x: x[1])[0] if any(daily_avgs.values()) else "N/A"
        worst_day = min(daily_avgs.items(), key=lambda x: x[1])[0] if any(daily_avgs.values()) else "N/A"

        doc = SimpleDocTemplate(
            output_path,
            pagesize=A4,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=45
        )

        styles = getSampleStyleSheet()
        normal = styles['Normal']

        title_style = ParagraphStyle(
            'HeaderTitle',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#00d4ff'),
            alignment=1
        )
        subtitle_style = ParagraphStyle(
            'HeaderSub',
            parent=normal,
            fontName='Helvetica',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#94a3b8'),
            alignment=1
        )
        section_style = ParagraphStyle(
            'SecTitle',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=16,
            textColor=colors.HexColor('#0f172a'),
            spaceBefore=10,
            spaceAfter=6
        )
        table_cell_style = ParagraphStyle(
            'TableCell',
            parent=normal,
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#1e293b')
        )
        table_cell_bold = ParagraphStyle(
            'TableCellB',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#0f172a')
        )

        elements = []

        # Header Block
        header_data = [
            [Paragraph(f"CodePulse Weekly Summary ({days} Days)", title_style)],
            [Paragraph("Aggregate Developer Telemetry & Flow Analytics", subtitle_style)]
        ]
        header_table = Table(header_data, colWidths=[A4[0] - 72])
        header_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#0a0e17')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 0), (-1, -1), 14),
            ('BOTTOMPADDING', (0, -1), (-1, -1), 14),
        ]))
        elements.append(header_table)
        elements.append(Spacer(1, 14))

        # Metrics Table
        elements.append(Paragraph("1. Aggregate Metrics", section_style))
        metrics_data = [
            [Paragraph("Total Sessions", table_cell_bold), Paragraph(str(total_sessions), table_cell_style),
             Paragraph("Total Coding Time", table_cell_bold), Paragraph(self._format_duration(total_time), table_cell_style)],
            [Paragraph("Average Flow Score", table_cell_bold), Paragraph(f"{avg_flow:.1f} / 100", table_cell_style),
             Paragraph("Best Day", table_cell_bold), Paragraph(best_day, table_cell_style)],
            [Paragraph("Period Window", table_cell_bold), Paragraph(f"Past {days} Days", table_cell_style),
             Paragraph("Lowest Day", table_cell_bold), Paragraph(worst_day, table_cell_style)],
        ]
        metrics_table = Table(metrics_data, colWidths=[130, 130, 130, 130])
        metrics_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f8fafc')),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(metrics_table)
        elements.append(Spacer(1, 18))

        # Chart Section: Trend Chart
        elements.append(Paragraph("2. Daily Flow Score Trend", section_style))
        chart_drawing = Drawing(480, 180)
        bc = VerticalBarChart()
        bc.x = 40
        bc.y = 25
        bc.height = 130
        bc.width = 400
        bc.data = [[round(v, 1) for v in daily_avgs.values()]]
        bc.categoryAxis.categoryNames = [k[5:] for k in daily_avgs.keys()]
        bc.categoryAxis.labels.fontSize = 8
        bc.valueAxis.valueMin = 0
        bc.valueAxis.valueMax = 100
        bc.valueAxis.valueStep = 20
        bc.bars[0].fillColor = colors.HexColor('#00d4ff')
        chart_drawing.add(bc)
        elements.append(chart_drawing)
        elements.append(Spacer(1, 14))

        # Daily Table
        elements.append(Paragraph("3. Daily Score Table", section_style))
        daily_table_rows = [
            [Paragraph("<b>Date</b>", table_cell_bold),
             Paragraph("<b>Sessions</b>", table_cell_bold),
             Paragraph("<b>Average Flow Score</b>", table_cell_bold)]
        ]
        for day_str in sorted(daily_buckets.keys(), reverse=True):
            sc_list = daily_buckets[day_str]
            avg_sc = sum(sc_list) / len(sc_list) if sc_list else 0.0
            daily_table_rows.append([
                Paragraph(day_str, table_cell_style),
                Paragraph(str(len(sc_list)), table_cell_style),
                Paragraph(f"{avg_sc:.1f} / 100" if sc_list else "--", table_cell_style)
            ])

        day_table = Table(daily_table_rows, colWidths=[173, 173, 174])
        day_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f1f5f9')),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(day_table)

        doc.build(elements, canvasmaker=NumberedCanvas)
        return output_path
